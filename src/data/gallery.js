// Vite glob import (JPG, JPEG, PNG, WEBP va JFIF kengaytmasidagi barcha rasmlarni yuklaydi)
const images = import.meta.glob("../assets/imgs/*.{jpg,jpeg,png,webp,jfif}", {
  eager: true,
  import: "default",
});

// Fayl nomidan kelib chiqib rasmni topuvchi yordamchi funksiya
const getImg = (name) => {
  const keys = Object.keys(images);
  // Birinchi navbatda fayl nomining o'zi bilan tamomila mos kelishini tekshiramiz
  const matchedKey = keys.find((key) => {
    const fileName = key.split("/").pop().split(".")[0].toLowerCase();
    return fileName === name.toLowerCase();
  });

  return matchedKey ? images[matchedKey] : "";
};

